_CHROMA_DIR = str(
    Path(__file__).resolve().parent.parent.parent / "storage" / "chroma_db"
)
_COLLECTION_NAME = "audit_documents"

_chroma_client = None
_chroma_collection = None
_embedding_fn = None


def _get_chroma():
    """Lazy initialise ChromaDB client and collection."""
    global _chroma_client, _chroma_collection, _embedding_fn

    if _chroma_collection is not None:
        return _chroma_collection

    try:
        import chromadb
        from chromadb.utils.embedding_functions import SentenceTransformerEmbeddingFunction

        Path(_CHROMA_DIR).mkdir(parents=True, exist_ok=True)
        _chroma_client = chromadb.PersistentClient(path=_CHROMA_DIR)
        _embedding_fn = SentenceTransformerEmbeddingFunction(
            model_name="all-MiniLM-L6-v2"
        )
        _chroma_collection = _chroma_client.get_or_create_collection(
            name=_COLLECTION_NAME,
            embedding_function=_embedding_fn,
            metadata={"hnsw:space": "cosine"},
        )
        logger.info(f"[SearchAgent] ChromaDB initialised at {_CHROMA_DIR}")
    except Exception as exc:
        logger.error(f"[SearchAgent] ChromaDB init failed: {exc}")
        _chroma_collection = None

    return _chroma_collection


